-- ── Helpers ────────────────────────────────────────────────────────────────
-- Admin = app_metadata.role = 'admin'. Unlike user_metadata, app_metadata can't be edited by users.
create or replace function public.is_admin() returns boolean
language sql stable as $$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'admin'
$$;

create or replace function public.set_updated_at() returns trigger
language plpgsql as $$
begin new.updated_at = now(); return new; end $$;

-- ── Products ───────────────────────────────────────────────────────────────
create table public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  price numeric(10,2) not null default 0,
  image text,
  category text not null default 'OTHERS',
  franchise text not null default 'Star Wars',
  brand text not null default 'Others',
  scale text not null default '1:6',
  condition text not null default 'Brand New',
  stock integer not null default 0,              -- always 0 for Lifesize (pre-order only)
  details text[] not null default '{}',
  new boolean not null default false,
  is_available boolean not null default true,
  is_hidden boolean not null default false,
  is_featured boolean not null default false,
  -- Pre-order fields (Lifesize figures)
  est_arrival text,                              -- e.g. '8–12 weeks'
  deposit_amount numeric(10,2),                  -- per unit; null = 30% default in the app
  sourcing_country text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger products_updated_at before update on public.products
for each row execute function public.set_updated_at();

alter table public.products enable row level security;
create policy "products_select_public" on public.products for select to anon, authenticated using (true);
create policy "products_insert_admin" on public.products for insert to authenticated with check (public.is_admin());
create policy "products_update_admin" on public.products for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "products_delete_admin" on public.products for delete to authenticated using (public.is_admin());

-- ── Orders ─────────────────────────────────────────────────────────────────
create table public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid references auth.users(id) on delete set null,
  -- snapshot of customer info at order time (for invoicing/shipping); NOT live profile data
  customer_name text not null default 'Guest',
  customer_email text,
  customer_phone text,
  status text not null default 'pending'
    check (status in ('pending','paid','deposit_paid','failed','cancelled','refunded')),
  order_type text not null default 'stock' check (order_type in ('stock','preorder')),
  payment_option text check (payment_option in ('full','deposit')),
  total numeric(10,2) not null,                  -- full order value
  amount_due_now numeric(10,2) not null default 0, -- what the customer pays at checkout (deposit or full)
  amount_paid numeric(10,2) not null default 0,  -- what has actually been received
  refunded_amount numeric(10,2) not null default 0,
  payment_method text,
  -- Pre-order & delivery tracking
  fulfillment_status text
    check (fulfillment_status in ('awaiting_order','ordered','in_transit','arrived','delivered')),
  est_arrival text,
  supplier_ref text,
  admin_notes text,
  ordered_at timestamptz,
  delivery_date date,
  delivery_time_slot text,
  courier_name text,
  tracking_number text,
  review_status text default 'accepted' check (review_status in ('pending', 'accepted', 'rejected')),
  created_at timestamptz not null default now()
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  category text not null,
  unit_price numeric(10,2) not null,
  quantity integer not null check (quantity > 0)
);

create index orders_fulfillment_idx on public.orders (order_type, fulfillment_status, status);
create index orders_created_idx on public.orders (created_at desc);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;

-- Guest checkout: anyone can create a PENDING order; nothing is paid or tracked yet.
create policy "orders_insert_public" on public.orders for insert to anon, authenticated
  with check (
    status = 'pending' and refunded_amount = 0 and amount_paid = 0
    and (fulfillment_status is null or fulfillment_status = 'awaiting_order')
    and supplier_ref is null and admin_notes is null and ordered_at is null
  );
create policy "order_items_insert_public" on public.order_items for insert to anon, authenticated
  with check (true);

-- Admin reads everything; a signed-in customer reads their own orders ("My Orders").
create policy "orders_select" on public.orders for select to authenticated
  using (public.is_admin() or customer_id = auth.uid());
create policy "order_items_select" on public.order_items for select to authenticated
  using (exists (select 1 from public.orders o
                 where o.id = order_id and (public.is_admin() or o.customer_id = auth.uid())));

-- Checkout can move a PENDING order forward; admin can update anything.
create policy "orders_update" on public.orders for update to anon, authenticated
  using (status = 'pending' or public.is_admin()) with check (true);

-- Non-admins may settle their own pending order or schedule delivery once arrived.
create or replace function public.orders_guard() returns trigger
language plpgsql as $$
begin
  if public.is_admin() then return new; end if;

  -- Allow customer to set/update their delivery date and time slot
  if old.customer_id = auth.uid()
     and new.total is not distinct from old.total
     and new.amount_paid is not distinct from old.amount_paid
     and new.status is not distinct from old.status
     and new.fulfillment_status is not distinct from old.fulfillment_status
     and new.amount_due_now is not distinct from old.amount_due_now
     and new.refunded_amount is not distinct from old.refunded_amount then
    return new;
  end if;

  -- Otherwise, validate standard customer checkout payment transitions
  if new.total is distinct from old.total
     or new.refunded_amount is distinct from old.refunded_amount
     or new.customer_id is distinct from old.customer_id
     or new.payment_method is distinct from old.payment_method
     or new.order_type is distinct from old.order_type
     or new.payment_option is distinct from old.payment_option
     or new.amount_due_now is distinct from old.amount_due_now
     or new.fulfillment_status is distinct from old.fulfillment_status
     or new.est_arrival is distinct from old.est_arrival
     or new.supplier_ref is distinct from old.supplier_ref
     or new.admin_notes is distinct from old.admin_notes
     or new.courier_name is distinct from old.courier_name
     or new.tracking_number is distinct from old.tracking_number
     or new.review_status is distinct from old.review_status
     or new.ordered_at is distinct from old.ordered_at then
    raise exception 'Not allowed';
  end if;

  if new.status not in ('paid','deposit_paid','failed','cancelled') then
    raise exception 'Not allowed';
  end if;
  if new.status = 'deposit_paid' and not (old.order_type = 'preorder' and old.payment_option = 'deposit') then
    raise exception 'Not allowed';
  end if;
  if new.amount_paid is distinct from old.amount_paid and new.amount_paid <> old.amount_due_now then
    raise exception 'Not allowed';
  end if;
  return new;
end $$;
create trigger orders_guard_trg before update on public.orders
for each row execute function public.orders_guard();

create policy "orders_delete_admin" on public.orders for delete to authenticated using (public.is_admin());

